export function translateKycOption(value: string, language: "en" | "ne"): string {
  if (language === "en") return value;
  const mapped = NEPALI_OPTION_LABELS[value];
  if (mapped) return mapped;

  const municipalityMatch = /^(.*) (Rural Municipality|Municipality)$/.exec(value);
  if (municipalityMatch) {
    const district = NEPALI_OPTION_LABELS[municipalityMatch[1]];
    if (district) {
      const suffix =
        municipalityMatch[2] === "Rural Municipality" ? " गाउँपालिका" : " नगरपालिका";
      return `${district}${suffix}`;
    }
  }
  return value;
}
